export function pollsForRace(raceSlug: string): PollRow[] {
  return POLLS.filter((item) => item.raceSlug === raceSlug);
}

export function ratingBoard() {
  return RATING_ORDER.map((tier) => ({
    tier,
    races: RACES.filter((race) => race.ratings.some((rating) => rating.tier === tier)),
  })).filter((column) => column.races.length > 0);
}
