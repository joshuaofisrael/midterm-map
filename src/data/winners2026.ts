import data from "./winners2026.json";
import meta from "./winners2026-meta.json";

export type WinnerCandidate = { name: string; party: string; votes: number; pct: number; winner: boolean };
export type RaceStatus = "called" | "uncalled" | "runoff";
export type WinnerRace = {
  slug: string; office: "Senate" | "House" | "Governor"; state: string; stateName: string; label: string;
  status: RaceStatus; apStatus: string | null; special: boolean; flipped: boolean; eevp: number | null;
  lastUpdated: string; calledAt: string | null; totalVotes: number;
  official: { label: string; href: string }; candidates: WinnerCandidate[];
};

/** When scripts/build-winners-2026.py last read the AP data. */
export const WINNERS_FETCHED_AT: string = (meta as { fetchedAt: string }).fetchedAt;

const ORDER = { Senate: 0, Governor: 1, House: 2 } as const;
/** Every 2026 Senate, governor and House general contest (generated by scripts/build-winners-2026.py). */
export const RACES_2026: WinnerRace[] = (data as WinnerRace[]).slice().sort(
  (a, b) => a.stateName.localeCompare(b.stateName) || ORDER[a.office] - ORDER[b.office] ||
    a.slug.localeCompare(b.slug, "en", { numeric: true }),
);
/** AP-called races only. */
export const WINNERS_2026: WinnerRace[] = RACES_2026.filter((w) => w.status === "called");
/** Races AP has not called, including runoffs. */
export const UNCALLED_2026: WinnerRace[] = RACES_2026.filter((w) => w.status !== "called");

export const getRace = (slug: string) => RACES_2026.find((w) => w.slug === slug);
export const getWinner = (slug: string) => WINNERS_2026.find((w) => w.slug === slug);
export const winnerOf = (w: WinnerRace) => w.candidates.find((c) => c.winner);
export const winnersForState = (code: string) => WINNERS_2026.filter((w) => w.state === code.toUpperCase());
export const racesForState = (code: string) => RACES_2026.filter((w) => w.state === code.toUpperCase());
export function nextWinner(slug: string) {
  const i = RACES_2026.findIndex((w) => w.slug === slug);
  return i < 0 ? undefined : RACES_2026[(i + 1) % RACES_2026.length];
}
export const winnerTitle = (w: WinnerRace) => `Who won the ${w.label} election 2026?`;
export function statusLine(w: WinnerRace) {
  return w.status === "runoff" ? "Heads to a runoff (AP)" : "Not yet called (AP)";
}
export function winnerDescription(w: WinnerRace) {
  const win = winnerOf(w);
  if (!win) {
    const d = w.status === "runoff"
      ? `The 2026 ${w.label} race heads to a runoff, per AP. Unofficial vote counts for every candidate and the official results link.`
      : `AP has not called the 2026 ${w.label} race yet. Unofficial vote counts for every candidate and the official results link.`;
    return d.length <= 160 ? d : d.slice(0, 157) + "...";
  }
  const d = `${win.name} (${win.party}) won the 2026 ${w.label} election with ${win.pct}% per AP. Every candidate's votes and share.`;
  return d.length <= 160 ? d : `${win.name} won the 2026 ${w.label} election per AP. Full candidate results.`.slice(0, 160);
}
export const etDate = (iso: string) =>
  new Date(iso).toLocaleString("en-US", { timeZone: "America/New_York", dateStyle: "long", timeStyle: "short" }) + " ET";
