const atlas = JSON.parse(readFileSync(path.join(root, "node_modules/us-atlas/states-10m.json"), "utf8"));
const collection = feature(atlas, atlas.objects.states);
const width = 960;
const height = 580;
const projection = geoAlbersUsa().fitExtent(
  [
    [8, 8],
    [width - 8, height - 8],
  ],
  collection,
);
const toPath = geoPath(projection);

