const rows = [];
for (const item of collection.features) {
  const id = String(item.id).padStart(2, "0");
  const code = FIPS[id];
  if (!code) continue;
  const d = toPath(item);
  if (!d) throw new Error(`No path for ${code}`);
  rows.push({ code, name: NAMES[code], d });
}
rows.sort((a, b) => a.code.localeCompare(b.code));
if (rows.length !== 51) throw new Error(`Expected 51 state paths, got ${rows.length}`);

const body = rows
  .map((row) => `  { code: "${row.code}", name: "${row.name}", d: ${JSON.stringify(row.d)} },`)
  .join("\n");
const file = `/** Simplified state shapes from the US Census cartographic boundary (us-atlas states-10m). Generated by scripts/write-us-map.mjs. */
export const US_MAP_VIEW = { width: ${width}, height: ${height} } as const;

export type StateMapPath = { code: string; name: string; d: string };

export const US_MAP_PATHS: StateMapPath[] = [
${body}
];
`;
const out = path.join(root, "src/data/usMapPaths.ts");
writeFileSync(out, file);
console.log(`Wrote ${rows.length} state paths to ${out}`);
